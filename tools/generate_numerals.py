"""Sample original Apache-2.0 Watch Clock SVG outlines into native polylines.

Control points: kiosk-satellite-watch-clock-screensaver/assets/clock/index.html.
Run from repository root. No SVG parser, font or image buffer on the device.
"""
from pathlib import Path
PATHS = [
    [(54,26), ('L',77,10), ('L',77,91)],
    [(90,29), ('C',91,3,129,1,134,23), ('C',141,45,111,62,91,89), ('L',137,89)],
    [(12,150), ('C',16,157,23,162,33,162), ('C',52,162,63,133,61,105),
     ('C',61,90,52,81,36,81), ('C',18,81,9,94,11,111),
     ('C',13,130,39,135,53,121), ('C',58,116,61,110,61,105)],
    [(147,91), ('C',158,78,181,80,187,94), ('C',194,111,181,120,162,121),
     ('C',184,120,194,132,187,149), ('C',180,167,156,165,145,151)],
    [(123,141), ('C',115,125,93,126,82,140), ('C',74,152,72,170,76,186),
     ('C',81,209,111,211,123,192), ('C',135,169,112,151,92,161),
     ('C',81,166,74,174,75,182)],
]
def sample(path):
    points = [path[0]]
    for cmd in path[1:]:
        if cmd[0] == 'L':
            points.append(cmd[1:])
        else:
            p = points[-1]
            for i in range(1,13):
                t, u = i/12, 1-i/12
                points.append(tuple(u**3*p[k]+3*u*u*t*cmd[1+k]+3*u*t*t*cmd[3+k]+t**3*cmd[5+k] for k in (0,1)))
    return points
def header():
    lines = ['// SPDX-License-Identifier: Apache-2.0', '// Generated by tools/generate_numerals.py.',
             '#pragma once', '#include "geometry.h"', 'namespace esphome::watch_clock::geometry {']
    for i,path in enumerate(PATHS):
        lines.append(f'inline constexpr Point NUMERAL_{i}[] = {{')
        lines.extend(f'  {{{x:.4f}f, {y:.4f}f}},' for x,y in sample(path))
        lines.append('};')
    lines.append('}  // namespace esphome::watch_clock::geometry\n')
    return '\n'.join(lines)
if __name__ == '__main__':
    Path('components/watch_clock/numerals.h').write_text(header(), encoding='utf-8')
